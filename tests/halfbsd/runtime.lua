function cases.credentials()
    assert(native.identity().euid==0)
    local user=ok(native.user('nobody'))
    local line=capture({helper,'identity'}, {user=user.uid,group=user.gid,groups={}})
    local _,_,_,uid,gid,groups=line:match('^(%d+) (%d+) (%d+) (%d+) (%d+) (%d+)')
    assert(tonumber(uid)==user.uid and tonumber(gid)==user.gid and tonumber(groups)==0)
    line=capture({helper,'identity'}, {user='nobody'})
    assert(tonumber(line:match('^%d+ %d+ %d+ (%d+)'))==user.uid)
end
