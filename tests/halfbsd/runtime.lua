local function ok(value, err)
    assert(value ~= nil, err and (err.operation .. ': ' .. err.message) or 'unexpected nil')
    return value
end
local function failure(value, err, name)
    assert(value == nil and type(err) == 'table' and type(err.code) == 'number')
    assert(err.operation and err.message and err.kind)
    if name then assert(err.name == name, err.name) end
end
local function run(args, opts)
    opts = opts or {}; opts.timeout = opts.timeout or 10
    local result = ok(proc.run(args, opts))
    assert(result.state == 'exited' and result.exit_code == 0, result.state)
    return result
end
local function rejects(fn) assert(not pcall(fn), 'invalid argument was accepted') end
local function capture(args, opts)
    opts = opts or {}; opts.stdout = 'pipe'; return run(args, opts).stdout
end
local function ready(child)
    local line = ok(child.stdout:read()); assert(line == 'ready\n', line)
end
