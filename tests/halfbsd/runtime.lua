function cases.lifecycle()
    local children={}
    for i=1,32 do children[i]=ok(proc.spawn({helper,'exit',tostring(i%7)})) end
    local index,result=proc.wait_any(children,10); assert(index and result.state=='exited')
    for i,c in ipairs(children) do assert(ok(c:wait(10)).exit_code==i%7) end
    local c=ok(proc.spawn({helper,'sleep','30'}))
    failure(proc.wait(c,0))
    ok(c:signal('TERM')); assert(ok(c:wait(10)).state=='signaled')
    assert(c:signal('TERM')==false and c:kill()==false)
    c=ok(proc.spawn({helper,'signal'}, {stdout='pipe'})); ready(c)
    ok(proc.signal(c,'USR1')); assert(ok(proc.wait(c,10)).success)
    c=ok(proc.spawn({helper,'ignore'}, {stdout='pipe',new_session=true})); ready(c)
    local result=ok(c:terminate(0.02,true)); assert(result.state=='signaled' and result.signal==9)
    c=ok(proc.spawn({helper,'group'}, {stdout='pipe',new_session=true}));ready(c)
    assert(ok(c:terminate(2,true)).success, 'group TERM did not reach descendant')
    local ids=capture({helper,'identity'}, {new_session=true})
    local pid,group,session=ids:match('^(%d+) (%d+) (%d+)'); assert(pid==group and pid==session)
    ids=capture({helper,'identity'}, {process_group=true});pid,group=ids:match('^(%d+) (%d+)');assert(pid==group)
    c=ok(proc.spawn({helper,'sleep','30'}));failure(proc.signal(c,'TERM',true))
    local found=false;for _,live in ipairs(proc.active()) do if live.pid==c.pid then found=true end end
    assert(found);ok(c:terminate(0.01))
    failure(proc.run({helper,'sleep','30'}, {timeout=0.02,grace=0.02}))
    -- Losing Lua handles neither kills services nor loses reaping ownership.
    local temp='gc-child'
    ok(proc.spawn({helper,'argv','survived'}, {stdout={path=temp}}))
    collectgarbage('collect')
    local loop=ok(event.new());loop:watch_timer(0.1,function() end);ok(loop:run());loop:close()
    local file=assert(io.open(temp));assert(file:read('*a')=='7375727669766564\n');file:close()
    for i=1,256 do assert(ok(proc.spawn({helper,'exit','0'})):wait(10).success) end
    ok(proc.shutdown(0.02))
end
function cases.events()
    local loop=ok(event.new());local calls=0
    loop:watch_timer(0.01,function(e) calls=calls+1;assert(e.id and e.count) end)
    ok(loop:run());assert(calls==1)
    local id=loop:watch_timer(0.01,function() error('cancelled timer ran') end)
    assert(loop:cancel(id) and not loop:cancel(id));assert(loop:step(0)==false)
    id=loop:watch_timer(0.01,function() calls=calls+1;loop:stop() end,true)
    ok(loop:run());assert(calls==2);loop:cancel(id)
    local child=ok(proc.spawn({helper,'exit','3'}));local delivered=false
    loop:watch_process(child,function(e) assert(e.result.exit_code==3 and e.target==child);delivered=true end)
    ok(loop:run());assert(delivered)
    -- Registration after exit still delivers a process result.
    ok(child:wait(10));delivered=false
    loop:watch_process(child,function(e) assert(e.result.exit_code==3);delivered=true end);ok(loop:run());assert(delivered)
    local read,write=proc.pipe(true);assert(read and write)
    id=loop:watch_read(read,function(e)assert(ok(read:read())=='readiness');assert(e.target==read);loop:cancel(e.id) end)
    loop:watch_write(write,function(e)ok(write:write('readiness'));loop:cancel(e.id) end)
    ok(loop:run());read:close();write:close()
    id=loop:watch_timer(0.001,function() error('expected callback failure') end)
    local value,err=loop:run();failure(value,err);assert(err.kind=='callback')
    local identity=native.identity()
    id=loop:watch_signal('USR2',function(e)assert(e.count>=1);loop:cancel(e.id) end)
    -- Deliver to this process using a directly spawned native utility.
    run({'/bin/kill','-USR2',tostring(identity.pid)})
    ok(loop:run())
    ok(native.atomic_replace('watched','before'))
    id=loop:watch_path('watched',function(e)assert(e.flags~=0);loop:cancel(e.id) end)
    ok(native.atomic_replace('watched','after'));ok(loop:run())
    loop:close();rejects(function() loop:step() end)
end
function cases.filesystem()
    assert(not native.exists('absent'))
    ok(native.mkdir('directory',0x1c0));assert(native.stat('directory').type=='directory')
    ok(native.atomic_replace('directory/file','one',0x180));ok(native.atomic_replace('directory/file','two',0x1a0))
    local file=assert(io.open('directory/file'));assert(file:read('*a')=='two');file:close()
    assert(native.stat('directory/file').mode==0x1a0)
    ok(native.chmod('directory/file',0x180));assert(native.stat('directory/file').mode==0x180)
    ok(native.symlink('file','directory/link'));assert(native.readlink('directory/link')=='file')
    assert(native.stat('directory/link').type=='symlink' and native.stat('directory/link',true).type=='file')
    ok(native.symlink('directory','alias'));failure(native.atomic_replace('alias/file','must not follow parent symlink'))
    failure(native.open('directory/link','write'))
    ok(native.atomic_replace('directory/link','replace link'))
    assert(native.stat('directory/link').type=='file')
    assert(native.user(native.identity().uid).uid==native.identity().uid)
    assert(native.group(native.identity().gid).gid==native.identity().gid)
    assert(native.clock('monotonic')>0 and native.clock('realtime')>0)
    assert(type(native.hostname())=='string')
    ok(native.setenv('HB_OS_TEST','value'));assert(native.getenv('HB_OS_TEST')=='value' and native.environment().HB_OS_TEST=='value')
    ok(native.setenv('HB_OS_TEST'));assert(native.getenv('HB_OS_TEST')==nil)
    -- Validate privileged API arguments without invoking privileged operations.
    rejects(function()native.mount('not a table')end)
    rejects(function()native.unmount('unused',-1)end)
    rejects(function()native.set_hostname('')end)
    rejects(function()native.set_clock(0,1000000000)end)
    ok(native.unlink('directory/file'));ok(native.unlink('directory/link'));ok(native.unlink('alias'));ok(native.rmdir('directory'))
end
